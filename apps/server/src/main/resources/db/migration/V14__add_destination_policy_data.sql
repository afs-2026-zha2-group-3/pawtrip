ALTER TABLE administrative_region
    ADD COLUMN policy_covered INTEGER NOT NULL DEFAULT 0
    CHECK (policy_covered IN (0, 1));

CREATE TABLE region_banned_breed (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    region_adcode TEXT NOT NULL,
    breed_name TEXT NOT NULL,
    source TEXT NOT NULL,
    updated TEXT NOT NULL,
    UNIQUE (region_adcode, breed_name),
    FOREIGN KEY (region_adcode) REFERENCES administrative_region(adcode) ON DELETE CASCADE
);

CREATE INDEX idx_region_banned_breed_region
    ON region_banned_breed(region_adcode);

UPDATE administrative_region
    SET policy_covered = 1
    WHERE adcode IN ('330100', '440400');

